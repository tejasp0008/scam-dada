#: A scam script. Entirely fictional, and every identifier in it is visibly fake: the UPI
#: handle is on `@demo` and the case number is prefixed FAKE.
SCAMMER_SCRIPT = (
    "Hello sir, main Delhi cyber crime branch se inspector Sharma bol raha hoon.",
    "Aapke naam par ek parcel pakda gaya hai, usme illegal items hain.",
    "Case number FAKE-CYB-0001 register ho gaya hai, abhi verify karna padega.",
    "Aap kisi ko bataiye mat, warrant nikal jayega aapke naam par.",
    "Verification ke liye fake.officer@demo par chhota amount bhej dijiye.",
    "Aap apne dada ji se baat karwaiye, mujhe unse hi baat karni hai.",
)

#: Not one of the persona voices: the scammer must not sound like the family.
SCAMMER_VOICE = "Shubham"

#: What the browser sends. Prisma's required rate.
WIRE_RATE = 16000
FRAME_SAMPLES = 512

#: Silence after each line, long enough for the energy VAD to close its gate - which is the
#: only end-of-speech signal there is, since Prisma does not emit `processing`.
GAP_SECONDS = 1.2

#: After that gap, keep sending silence until the persona has stopped talking. A real
#: scammer waits for a reply before starting his next sentence; a driver on a fixed timer
#: talks over every answer, which makes barge-in fire constantly and the transcript
#: unreadable. Capped so a persona that never stops cannot stall the script.
WAIT_FOR_PERSONA_SECONDS = 14.0

#: How long the line has to be quiet before the persona counts as finished.
#:
#: Longer than it looks like it needs to be, because a reply is spoken sentence by sentence
#: and the gap *inside* one reply - synthesise, render, hand over - runs to about a second.
#: At 0.8 s the driver decided he had finished after his first sentence and talked over the
#: rest, which showed up as three barge-ins and replies truncated to four words. A human
#: waits longer than this before assuming someone is done.
PERSONA_QUIET_SECONDS = 2.0

#: RMS above which inbound audio counts as the persona *speaking* rather than as the room
#: tone that now plays continuously between utterances.
#:
#: Without this the driver never sees a quiet line, waits out its full timeout every turn and
#: then talks over the reply anyway - which on one run produced three barge-ins and three
#: caller turns with no answer at all. The bed sits near 0.012 RMS and speech near 0.07, so
#: the gap is wide and this threshold is not delicate.
SPEECH_RMS = 0.03


def is_speech(pcm: bytes) -> bool:
    """Whether a chunk of inbound audio is the persona talking, not the room."""
    samples = pcm_to_float32(pcm)
    if samples.size == 0:
        return False
    return bool(np.sqrt(np.mean(np.square(samples.astype(np.float64)))) >= SPEECH_RMS)


async def synthesise_script(lines: tuple[str, ...]) -> list[np.ndarray]:
    """Render the scammer's lines to 16 kHz mono, through the cache."""
    settings = get_settings()
    if not settings.gnani_api_key:
        print("GNANI_API_KEY is not set in .env", file=sys.stderr)
        raise SystemExit(2)

    engine = create_engine(settings)
    sessions = create_session_factory(engine)
    redis = create_redis(settings)
    budget = BudgetGuard(redis, sessions, settings)
    rendered: list[np.ndarray] = []

    async with httpx.AsyncClient() as client:
        tts = CachingTTS(
            GnaniTimbreTTS(
                api_key=settings.gnani_api_key,
                sse_url=settings.gnani_tts_sse_url,
                model=settings.tts_model,
                language=settings.tts_language,
                client=client,
                usage=budget,
                read_timeout=60.0,
            ),
            settings.tts_cache_dir,
            usage=budget,
        )
        for line in lines:
            pcm = bytearray()
            async for chunk in tts.synthesize(
                TtsRequest(
                    text=line,
                    voice=SCAMMER_VOICE,
                    language=settings.tts_language,
                    model=settings.tts_model,
                    sample_rate=24000,
                )
            ):
                pcm.extend(chunk.pcm)
            rendered.append(resample_linear(pcm_to_float32(bytes(pcm)), 24000, WIRE_RATE))
        print(f"Scammer script: {tts.misses} synthesised, {tts.hits} from cache")

    status = await budget.status(BillingPool.GNANI)
    await redis.aclose()
    await engine.dispose()
    print(f"Gnani pool at {status.spent:.4f} credits of a {status.stop_at:g} hard stop\n")
    return rendered


def frames(samples: np.ndarray) -> list[bytes]:
    """Split audio into the exact 1024-byte frames the wire expects."""
    padded = np.pad(samples, (0, (-samples.size) % FRAME_SAMPLES))
    return [
        float32_to_pcm(padded[i : i + FRAME_SAMPLES]) for i in range(0, padded.size, FRAME_SAMPLES)
    ]


async def run_call(url: str, lines: list[np.ndarray], out: Path) -> int:
    """Play the script down the socket and collect everything that comes back."""
    received = bytearray()
    events: list[dict[str, object]] = []
    flushes = 0
    call_id = ""
    last_audio = 0.0
    # (offset in seconds from the start of the call, audio). Recorded for both sides so the
    # whole conversation can be laid back onto one timeline afterwards. The persona-only
    # file is a recording of half a phone call; this is the call.
    timeline: list[tuple[float, np.ndarray, str]] = []
    call_started = 0.0
    # When the persona's audio will have finished *playing*, not when it last arrived. The
    # server hands a whole sentence over in milliseconds and it then plays for ten seconds,
    # so a driver that waits on arrival starts talking almost immediately and barges in on
    # every reply - which is the same mistake the server made with `speaking`.
    speech_until = 0.0

    async with websockets.connect(url, max_size=None) as socket:

        async def listen() -> None:
            nonlocal flushes, call_id, last_audio, speech_until
            async for message in socket:
                if isinstance(message, bytes):
                    received.extend(message)
                    now = time.monotonic()
                    # Room tone belongs in the recording but not in turn-taking: the line is
                    # never silent now, so "has he stopped" has to mean "stopped speaking".
                    if is_speech(message):
                        last_audio = now
                        seconds = len(message) / 2 / 24000
                        speech_until = max(speech_until, now) + seconds
                    timeline.append((now - call_started, pcm_to_float32(message), "persona"))
                    continue
                payload = json.loads(message)
                kind = payload.get("type")
                if kind == "ready":
                    call_id = str(payload["call_id"])
                    print(f"call {call_id}")
                elif kind == "flush":
                    flushes += 1
                    print("  <- barge-in: playback flushed")
                elif kind == "event":
                    events.append(payload["event"])
                    _print_event(payload["event"])
                elif kind == "ready" and payload.get("canary"):
                    canary = payload["canary"]
                    print(f"  canary issued: {canary['full_name']} / {canary['upi_handle']}")
                elif kind == "error":
                    print(f"  <- error: {payload['message']}", file=sys.stderr)
                elif kind == "ended":
                    print(f"  <- ended: {payload.get('reason')}")
                    return

        reader = asyncio.create_task(listen())
        silence = float32_to_pcm(np.zeros(FRAME_SAMPLES, dtype=np.float32))
        call_started = time.monotonic()

        async def hold(seconds: float) -> None:
            """Send silence for `seconds`, keeping the line open and the VAD fed."""
            for _ in range(int(seconds * WIRE_RATE / FRAME_SAMPLES)):
                await socket.send(silence)
                await asyncio.sleep(FRAME_SAMPLES / WIRE_RATE)

        for index, line in enumerate(lines, start=1):
            print(f"  -> scammer line {index}/{len(lines)}")
            timeline.append((time.monotonic() - call_started, line, "caller"))
            for frame in frames(line):
                await socket.send(frame)
                # Real time, because the whole loop is timing: the VAD, the barge-in window
                # and the latency numbers all mean nothing if the audio arrives instantly.
                await asyncio.sleep(FRAME_SAMPLES / WIRE_RATE)
            await hold(GAP_SECONDS)

            waited = 0.0
            while waited < WAIT_FOR_PERSONA_SECONDS:
                now = time.monotonic()
                finished_playing = now >= speech_until
                quiet_long_enough = bool(last_audio) and now - last_audio > PERSONA_QUIET_SECONDS
                if finished_playing and quiet_long_enough:
                    break
                await hold(0.2)
                waited += 0.2

        await socket.send("hangup")
        try:
            await asyncio.wait_for(reader, timeout=20.0)
        except TimeoutError:
            reader.cancel()

    name = (call_id or "call")[:8]
    if received:
        path = out / f"{name}.persona.wav"
        path.write_bytes(pcm_to_wav(bytes(received), 24000))
        print(f"\nPersona audio: {len(received) / 2 / 24000:.1f}s -> {path}")
    if timeline:
        _write_conversation(timeline, out, name)
    (out / f"{name}.events.json").write_text(json.dumps(events, indent=2))

    def of(kind: str) -> list[dict[str, object]]:
        return [e for e in events if e.get("type") == kind]

    latency = of("latency")
    print(
        f"Events: {len(events)}  transcripts: {len(of('transcript'))}  "
        f"handoffs: {len(of('persona_handoff'))}  entities: {len(of('entity'))}  "
        f"leaks: {len(of('canary_match'))}"
    )
    if stages := of("stage"):
        print(f"Final stage: {stages[-1].get('stage')}")
    if entities := of("entity"):
        print("Extracted:")
        for entity in entities:
            print(
                f"  {entity.get('entity_type'):16} {entity.get('value')!r} [{entity.get('source')}]"
            )
    print(f"Barge-ins: {flushes}")
    if latency:
        _print_latency(latency)
    if not received:
        print("\nNo persona audio came back.", file=sys.stderr)
        return 1
    return 0


#: A gap longer than this between persona chunks starts a new utterance. The server sends a
#: sentence as a burst of 60 ms slices, so the gaps *within* an utterance are milliseconds
#: and the gaps *between* them are the LLM and the synthesiser - hundreds at least.
UTTERANCE_GAP_SECONDS = 0.35


def _group_persona(
    pieces: list[tuple[float, np.ndarray]], rate: int
) -> list[tuple[float, np.ndarray]]:
    """Reassemble persona chunks into utterances laid down contiguously.

    This is the correction that makes the recording honest. The server pushes a sentence as
    fast as the socket accepts it, so chunk *arrival* times cluster - placing each chunk at
    its own arrival offset stacks a sentence on top of itself. What the listener actually
    hears is the browser's ring buffer playing those chunks back to back, so an utterance is
    laid down contiguously from the moment its first chunk arrived.
    """
    grouped: list[tuple[float, np.ndarray]] = []
    current: list[np.ndarray] = []
    start = 0.0
    previous = 0.0

    for offset, audio in pieces:
        if current and offset - previous > UTTERANCE_GAP_SECONDS:
            grouped.append((start, np.concatenate(current)))
            current = []
        if not current:
            start = offset
        current.append(audio)
        previous = offset
    if current:
        grouped.append((start, np.concatenate(current)))
    return grouped


def _fit(track: np.ndarray, ceiling: float = 0.95) -> float:
    """Scale factor that brings a track under `ceiling`, never above 1.0.

    Only ever attenuates. Normalising upwards would hide a persona that is genuinely too
    quiet against the caller, and the relative level of the two sides is part of what is
    being reviewed.
    """
    peak = float(np.max(np.abs(track))) if track.size else 0.0
    return min(1.0, ceiling / peak) if peak > ceiling else 1.0


def _write_conversation(
    timeline: list[tuple[float, np.ndarray, str]], out: Path, name: str
) -> None:
    """Lay both sides of the call back onto one timeline and write it out.

    Two files, because they answer different questions:

    * **mono** is what the call sounded like, and what goes into a demo video.
    * **stereo** puts the caller left and the persona right, which is the only practical way
      to review who interrupted whom - and barge-in is the thing most worth reviewing.

    Offsets are wall-clock from the start of the call, which is the right clock: the point of
    this project is how much of a scammer's real time was consumed, and a timeline built from
    audio lengths alone would silently delete every silence.
    """
    rate = 24000
    caller_pieces = [
        (offset, resample_linear(audio, WIRE_RATE, rate))
        for offset, audio, who in timeline
        if who == "caller"
    ]
    persona_pieces = _group_persona(
        [(offset, audio) for offset, audio, who in timeline if who == "persona"], rate
    )
    # Room tone belongs in the mix but is not an "utterance", and counting it as one made
    # the summary claim more seconds of speech than the call was long.
    spoken_pieces = [
        (offset, audio)
        for offset, audio in persona_pieces
        if float(np.sqrt(np.mean(np.square(audio.astype(np.float64))))) >= SPEECH_RMS
    ]
    if not caller_pieces and not persona_pieces:
        return

    everything = [(o, a) for o, a in caller_pieces] + [(o, a) for o, a in persona_pieces]
    total = max(int((offset + audio.size / rate) * rate) for offset, audio in everything) + rate
    caller = np.zeros(total, dtype=np.float32)
    persona = np.zeros(total, dtype=np.float32)

    for track, pieces in ((caller, caller_pieces), (persona, persona_pieces)):
        for offset, audio in pieces:
            start = max(0, int(offset * rate))
            end = min(total, start + audio.size)
            track[start:end] += audio[: end - start]

    # One factor for both tracks, derived from the mix, so no sample clips and the balance
    # between the two sides is preserved exactly.
    gain = _fit(caller + persona)
    mono_path = out / f"{name}.call.wav"
    mono_path.write_bytes(pcm_to_wav(float32_to_pcm((caller + persona) * gain), rate))

    interleaved = np.empty(total * 2, dtype=np.float32)
    interleaved[0::2] = caller * gain
    interleaved[1::2] = persona * gain
    stereo_path = out / f"{name}.stereo.wav"
    stereo_path.write_bytes(pcm_to_wav(float32_to_pcm(interleaved), rate, channels=2))

    speech = sum(audio.size for _, audio in spoken_pieces) / rate
    print(f"Whole call:    {total / rate:.1f}s -> {mono_path}")
    print(f"               {len(spoken_pieces)} persona utterances, {speech:.1f}s of speech")
    print(f"               caller left / persona right -> {stereo_path}")


def _print_event(event: dict[str, object]) -> None:
    kind = event.get("type")
    if kind == "transcript":
        who = event.get("persona") or "caller"
        print(f"  <- [{who}] {event.get('text')}")
    elif kind == "state_change":
        print(f"  <- state: {event.get('from_state')} -> {event.get('to_state')}")
    elif kind == "persona_handoff":
        print(f"  <- handoff: {event.get('from_persona')} -> {event.get('to_persona')}")
    elif kind == "stage":
        print(
            f"  <- stage: {event.get('stage')} "
            f"(confidence {event.get('confidence')}, pressure {event.get('pressure_score')})"
        )
    elif kind == "entity":
        print(
            f"  <- entity [{event.get('source')}] {event.get('entity_type')} = "
            f"{event.get('value')!r}"
        )
    elif kind == "risk":
        raw = event.get("signals")
        named = raw if isinstance(raw, list) else []
        signals = ", ".join(str(item) for item in named) or "none"
        tactic = event.get("tactic") or "none"
        print(f"  <- risk: {event.get('hangup_risk')} [{signals}] tactic={tactic}")
    elif kind == "canary_match":
        print(
            f"  <- LEAK: {event.get('matched_field')} {event.get('matched_text')!r} was "
            f"issued to call {str(event.get('issued_call_id'))[:8]}"
        )


def _print_latency(latency: list[dict[str, object]]) -> None:
    def ms(event: dict[str, object], key: str) -> str:
        value = event.get(key)
        return f"{value}" if isinstance(value, int) else "-"

    print("\nPer-turn latency (ms), measured from the caller stopping speaking:")
    print(f"  {'turn':>4}  {'stt':>6}  {'llm':>6}  {'tts':>6}  filler")
    for event in latency:
        print(
            f"  {event.get('turn_seq'):>4}  {ms(event, 'stt_final_ms'):>6}  "
            f"{ms(event, 'llm_first_token_ms'):>6}  {ms(event, 'tts_first_byte_ms'):>6}  "
            f"{'yes' if event.get('filler_played') else 'no'}"
        )


async def _latest_canary() -> str | None:
    """The UPI handle of the most recently issued canary, if there is one.

    Read straight from the database rather than remembered between runs, so the leak demo
    works on a fresh checkout after a single ordinary call.
    """
    from sqlalchemy import select

    from app.infra.db import create_engine, create_session_factory
    from app.infra.models_sql import CanaryIdentity as CanaryRow

    settings = get_settings()
    engine = create_engine(settings)
    sessions = create_session_factory(engine)
    try:
        async with sessions() as session:
            rows = await session.execute(
                select(CanaryRow).order_by(CanaryRow.issued_at.desc()).limit(1)
            )
            row = rows.scalars().first()
            if row is None:
                return None
            handle = row.identity.get("upi_handle")
            return str(handle) if handle else None
    finally:
        await engine.dispose()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--url", default="ws://127.0.0.1:8000/ws/call")
    parser.add_argument("--out", type=Path, default=Path("var/calls"))
    parser.add_argument("--lines", type=int, default=len(SCAMMER_SCRIPT))
    parser.add_argument(
        "--leak",
        action="store_true",
        help="have the scammer quote a canary identity issued to an earlier call, which is "
        "what a shared lead list looks like from our side",
    )
    args = parser.parse_args()

    configure_logging(get_settings().log_level)
    args.out.mkdir(parents=True, exist_ok=True)
    script = SCAMMER_SCRIPT[: max(1, args.lines)]
    if args.leak:
        leaked = asyncio.run(_latest_canary())
        if leaked is None:
            print("no earlier canary to leak; run a call without --leak first", file=sys.stderr)
            return 2
        # Spoken as a scammer reading from a list, which is exactly the scenario.
        script = (*script, f"Humare record mein aapka handle {leaked} hai, wahi confirm kijiye.")
        print(f"Leaking a canary from an earlier call: {leaked}\n")
    print(f"Driving a {len(script)}-line call at {args.url}\n")
    return asyncio.run(_drive(args.url, script, args.out))


async def _drive(url: str, script: tuple[str, ...], out: Path) -> int:
    lines = await synthesise_script(script)
    started = time.perf_counter()
    code = await run_call(url, lines, out)
    print(f"Wall clock: {time.perf_counter() - started:.1f}s")
    return code


if __name__ == "__main__":
    raise SystemExit(main())
