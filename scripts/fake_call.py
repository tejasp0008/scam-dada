"""Drive a whole call over the WebSocket with a scripted scammer. No microphone needed.

This exists for three reasons:

1. **Verification.** It exercises the real transport, the real orchestrator and whichever
   providers are configured, which a unit test cannot.
2. **A reproducible demo.** A recorded take that depends on someone speaking into a laptop
   is not reproducible; this one is, and it can be re-run after a change to see whether the
   change helped.
3. **Cost.** The scammer's lines are synthesised through the same content-hash TTS cache as
   everything else, so after the first run the scammer's half of the call is free.

The scammer's audio is generated by Timbre in a *different* voice from the personas and then
resampled to 16 kHz, which is what the browser sends. It is synthetic from end to end: no
recording of a real call exists anywhere in this project.

    python scripts/fake_call.py                      # against a server on :8000
    python scripts/fake_call.py --url ws://host/ws/call --out var/calls
"""

